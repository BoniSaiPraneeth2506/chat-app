/** 0 = default, 1..5 = light..dark. */
export const SKIN_TONE_LABELS = ["Default", "Light", "Medium-light", "Medium", "Medium-dark", "Dark"];
export const SKIN_TONE_SUFFIXES = ["", "\u{1F3FB}", "\u{1F3FC}", "\u{1F3FD}", "\u{1F3FE}", "\u{1F3FF}"];

export function applySkinTone(emoji, toneIndex) {
  if (toneIndex <= 0) return emoji;
  const stripped = emoji.replace(/[\u{1F3FB}-\u{1F3FF}]/gu, "");
  if (TONE_BASE.has(stripped)) {
    return stripped + SKIN_TONE_SUFFIXES[toneIndex];
  }
  return emoji;
}

