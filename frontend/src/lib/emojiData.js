export const EMOJI_KEYWORDS = SEARCH_KEYWORDS;

const FREQ_KEY = "chatty:frequentEmojis";

export function getFrequentEmojis(limit = 24) {
  try {
    const raw = localStorage.getItem(FREQ_KEY);
    const arr = raw ? JSON.parse(raw) : [];
    return Array.isArray(arr) ? arr.filter((e) => typeof e === "string").slice(0, limit) : [];
  } catch {
    return [];
  }
}

export function pushFrequentEmoji(emoji) {
  try {
    const prev = getFrequentEmojis(48);
    const next = [emoji, ...prev.filter((e) => e !== emoji)].slice(0, 48);
    localStorage.setItem(FREQ_KEY, JSON.stringify(next));
  } catch {
    /* storage unavailable — recents just don't persist */
  }
}

export function searchEmojis(query) {
  const q = query.trim().toLowerCase();
  if (!q) return null;
  const fromKeywords = Object.entries(SEARCH_KEYWORDS)
    .filter(([word]) => word.includes(q) || q.includes(word))
    .map(([, emoji]) => emoji);
  const fromText = [];
  for (const cat of EMOJI_CATEGORIES) {
    for (const emoji of cat.emojis) {
      if (fromText.length >= 60) break;
      if (emoji.includes(q)) fromText.push(emoji);
    }
  }
  const unique = [...new Set([...fromKeywords, ...fromText])];
  return unique.length ? unique.slice(0, 60) : [];
}